"""Pydantic v2 request/response schemas (public API field names are in English)."""

from datetime import date
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

EMAIL_PATTERN = r"^[^@\s]+@[^@\s]+\.[^@\s]+$"

Technique = Literal["zero_shot", "few_shot", "cot"]


# ---------- Members ----------

class MemberCreate(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "name": "Laura Gomez",
                    "email": "laura.gomez@example.com",
                    "phone": "+57 300 123 4567",
                    "active": True,
                }
            ]
        }
    )

    name: str = Field(min_length=2, max_length=100, description="Member full name.")
    email: str = Field(max_length=120, pattern=EMAIL_PATTERN, description="Unique email address.")
    phone: str | None = Field(default=None, max_length=20, description="Contact phone number.")
    active: bool = Field(default=True, description="Whether the member is currently active.")


class MemberUpdate(BaseModel):
    """All fields are optional: only the fields sent are updated."""

    model_config = ConfigDict(
        json_schema_extra={"examples": [{"phone": "+57 310 555 0000", "active": False}]}
    )

    name: str | None = Field(default=None, min_length=2, max_length=100, description="Member full name.")
    email: str | None = Field(
        default=None, max_length=120, pattern=EMAIL_PATTERN, description="Unique email address."
    )
    phone: str | None = Field(default=None, max_length=20, description="Contact phone number.")
    active: bool | None = Field(default=None, description="Whether the member is currently active.")


class MemberOut(BaseModel):
    model_config = ConfigDict(
        from_attributes=True,
        populate_by_name=True,
        json_schema_extra={
            "examples": [
                {
                    "id": 1,
                    "name": "Laura Gomez",
                    "email": "laura.gomez@example.com",
                    "phone": "+57 300 123 4567",
                    "registered_at": "2026-10-19",
                    "active": True,
                }
            ]
        },
    )

    # validation_alias maps the Spanish ORM attribute names to the English API fields.
    id: int
    name: str = Field(validation_alias="nombre")
    email: str
    phone: str | None = Field(default=None, validation_alias="telefono")
    registered_at: date = Field(validation_alias="fecha_registro")
    active: bool = Field(validation_alias="activo")


# ---------- Errors ----------

class ErrorOut(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {"error": "Not Found", "detail": "Member with id 42 was not found.", "status": 404}
            ]
        }
    )

    error: str = Field(description="Short HTTP error name.")
    detail: Any = Field(description="Human-readable message or list of validation problems.")
    status: int = Field(description="HTTP status code.")


# ---------- AI ----------

class AIRequest(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "question": "Which exercises in my routine train the chest?",
                    "technique": "few_shot",
                    "member_id": 1,
                }
            ]
        }
    )

    question: str = Field(min_length=3, max_length=1000, description="User question for the assistant.")
    technique: Technique = Field(
        default="zero_shot", description="Prompting technique: zero_shot, few_shot or cot."
    )
    member_id: int | None = Field(
        default=None, description="Optional member id used to retrieve personal context (RAG)."
    )


class AIResponse(BaseModel):
    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "answer": "Your routine trains the chest with Bench Press (4x8) and Push-ups (3x15).",
                    "technique": "few_shot",
                    "sources": ["member:1", "routine:1", "exercise:1", "exercise:3"],
                    "input_tokens": 412,
                    "output_tokens": 58,
                    "latency_ms": 1240,
                }
            ]
        }
    )

    answer: str = Field(description="Answer generated by the LLM.")
    technique: Technique = Field(description="Prompting technique used.")
    sources: list[str] = Field(description="Database records used as context (RAG).")
    input_tokens: int = Field(description="Prompt tokens reported by the provider.")
    output_tokens: int = Field(description="Generated tokens reported by the provider (including thinking).")
    latency_ms: int = Field(description="LLM call latency in milliseconds.")
